#!/usr/bin/env python3
"""Inventory every media file in this repository into ASSETS.md.

Reads real numbers from ffprobe (via the vendored ffmpeg-skill probe.py), never
from file names. Re-run it after adding footage:

    python3 tools/inventory.py            # rewrites ASSETS.md
    python3 tools/inventory.py --json     # machine-readable on stdout instead
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROBE = ROOT / "tools" / "ffmpeg-skill" / "scripts" / "probe.py"
VIDEO_EXT = {".mp4", ".mov", ".mkv", ".webm", ".m4v", ".avi"}
AUDIO_EXT = {".mp3", ".wav", ".m4a", ".aac", ".flac", ".ogg", ".opus", ".mpeg"}
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".heic"}
SKIP_DIRS = {"tools", ".tools", ".git", "out", "projects", "node_modules"}


def media_files() -> list[Path]:
    files = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in (VIDEO_EXT | AUDIO_EXT | IMAGE_EXT):
            continue
        if SKIP_DIRS & set(path.relative_to(ROOT).parts):
            continue
        files.append(path)
    return files


def probe(path: Path) -> dict:
    out = subprocess.run(
        [sys.executable, str(PROBE), str(path), "--json"],
        capture_output=True, text=True, check=False,
    )
    if out.returncode != 0:
        return {"error": (out.stderr or out.stdout).strip().splitlines()[-1:] or ["probe failed"]}
    payload = json.loads(out.stdout)
    fmt = path.suffix.lower()
    if fmt in IMAGE_EXT:
        payload["kind"] = "image"
    elif fmt in AUDIO_EXT or not payload.get("video"):
        payload["kind"] = "audio"
    else:
        payload["kind"] = "video"
    return payload


def human_bytes(n: int | float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit in ("B", "KB") else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} GB"


def hhmmss(seconds: float) -> str:
    m, s = divmod(round(seconds), 60)
    h, m = divmod(m, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def orientation(video: dict | None) -> str:
    if not video:
        return "-"
    w, h = video["width"], video["height"]
    if abs(w - h) / max(w, h) < 0.02:
        return "square"
    return "vertical" if h > w else "horizontal"


def summarise(path: Path, data: dict) -> dict:
    video = data.get("video") or None
    audio = data.get("audio") or None
    duration = data.get("duration") or 0
    return {
        "file": str(path.relative_to(ROOT)),
        "kind": data.get("kind", "video"),
        "duration_s": round(duration, 2),
        "duration": hhmmss(duration) if duration else "-",
        "resolution": f"{video['width']}x{video['height']}" if video else "-",
        "fps": video.get("fps") if video else None,
        "aspect": video.get("display_aspect") if video else None,
        "orientation": orientation(video),
        "audio": ("yes" if audio else "no") if video else "-",
        "audio_channels": audio.get("channels") if audio else None,
        "size": human_bytes(data.get("size_bytes", path.stat().st_size)),
        "size_bytes": data.get("size_bytes", path.stat().st_size),
        "codec": (video or audio or {}).get("codec"),
        "error": data.get("error"),
    }


def as_markdown(rows: list[dict]) -> str:
    lines = [
        "# Asset inventory",
        "",
        "Generated by `python3 tools/inventory.py` — every number below comes from ffprobe,",
        "not from the file name. Re-run after adding footage.",
        "",
    ]
    groups = [
        ("Video", "video"),
        ("Audio", "audio"),
        ("Stills", "image"),
    ]
    for title, kind in groups:
        subset = [r for r in rows if r["kind"] == kind]
        if not subset:
            continue
        lines.append(f"## {title} ({len(subset)})")
        lines.append("")
        if kind == "video":
            lines += [
                "| File | Length | Resolution | Aspect | FPS | Shot | Audio | Size |",
                "|---|---|---|---|---|---|---|---|",
            ]
            for r in subset:
                fps = f"{r['fps']:.2f}".rstrip("0").rstrip(".") if r["fps"] else "-"
                lines.append(
                    f"| `{r['file']}` | {r['duration']} | {r['resolution']} | {r['aspect']} "
                    f"| {fps} | {r['orientation']} | {r['audio']} | {r['size']} |"
                )
        elif kind == "audio":
            lines += ["| File | Length | Codec | Channels | Size |", "|---|---|---|---|---|"]
            for r in subset:
                lines.append(
                    f"| `{r['file']}` | {r['duration']} | {r['codec']} "
                    f"| {r['audio_channels'] or '-'} | {r['size']} |"
                )
        else:
            lines += ["| File | Resolution | Size |", "|---|---|---|"]
            for r in subset:
                lines.append(f"| `{r['file']}` | {r['resolution']} | {r['size']} |")
        lines.append("")

    total = sum(r["size_bytes"] for r in rows)
    video_rows = [r for r in rows if r["kind"] == "video"]
    runtime = sum(r["duration_s"] for r in video_rows)
    vertical = sum(1 for r in video_rows if r["orientation"] == "vertical")
    errors = [r for r in rows if r["error"]]
    lines += [
        "## Totals",
        "",
        f"- {len(video_rows)} video files, {len([r for r in rows if r['kind'] == 'audio'])} audio, "
        f"{len([r for r in rows if r['kind'] == 'image'])} stills — {human_bytes(total)} on disk.",
        f"- {hhmmss(runtime)} of footage; {vertical} vertical clip(s), "
        f"{len(video_rows) - vertical} horizontal/square.",
        "",
        "## Notes for editing",
        "",
        "- Sources are stock clips with mixed frame rates and resolutions; `fit.py` conforms",
        "  them to one delivery spec (aspect, fps, codec) in a single pass.",
        "- Any clip whose `Audio` column says `yes` with no dialogue is ambience — drop it and",
        "  lay the music bed + voiceover instead.",
        "- `background song.mpeg` holds MP3 audio despite the extension; `audio.py --music` reads",
        '  it directly (the demo reel does). Convert to WAV only if you want lossless re-edits.',
        "- `benjamin voice.mp3` holds mono Opus despite the extension; the mixing tools read it",
        "  as-is and upmix to stereo with `--stereo`.",
    ]
    if errors:
        lines += ["", "## Unreadable files", ""]
        lines += [f"- `{r['file']}` — {r['error']}" for r in errors]
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", action="store_true", help="print JSON instead of writing ASSETS.md")
    args = ap.parse_args()

    rows = [summarise(p, probe(p)) for p in media_files()]
    if args.json:
        print(json.dumps(rows, indent=2))
        return 0
    out = ROOT / "ASSETS.md"
    out.write_text(as_markdown(rows), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} — {len(rows)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
